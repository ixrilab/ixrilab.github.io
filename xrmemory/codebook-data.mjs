export function criterionState(item,checks){
 if(item.any){const s=item.any.map(x=>criterionState(x,checks));return s.includes('yes')?'yes':s.every(x=>x==='no')?'no':s.includes('unsure')?'unsure':'unset';}
 return ['yes','no','unsure'].includes(checks[item.id])?checks[item.id]:'unset';
}
export function routeState(route,checks){const s=route.items.map(x=>criterionState(x,checks));return s.includes('no')?'no':s.every(x=>x==='yes')?'yes':s.includes('unsure')?'unsure':'unset';}
export function scopeState(checks){const passing=ROUTES.filter(r=>routeState(r,checks)==='yes').map(r=>r.id);return {passing,state:passing.length?'yes':ROUTES.every(r=>routeState(r,checks)==='no')?'no':'incomplete'};}
export function leafItems(route){return route.items.flatMap(x=>x.any||[x]);}
